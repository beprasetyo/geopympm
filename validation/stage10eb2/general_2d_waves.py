"""Stage 10E-B2: 2D force-driven mixed P/S-wave verification.

Two oblique plane waves (longitudinal + transverse), with different wave
vectors, constitute an INDEPENDENT exact solution of the *linearized*
plane-strain elastodynamic equations. Initial stress is zero; initial particle
velocity is nonuniform in both spatial directions. ALL interior velocities
are subsequently generated by the MPM force/momentum update, with NO
prescribed nodal velocity boundary conditions. The wide finite particle block
is traction-free; error is measured in a central window during a short-time
interval before disturbances from free faces can reach it.

IMPORTANT: the analytic solution is not an exact solution of the finite-strain
Jaumann hypoelastic model used in the solver; finite-amplitude comparisons
therefore include constitutive/model differences in addition to discretization
error. A separate amplitude sweep probes the expected linearization error.

Run: python -m validation.stage10eb2.general_2d_waves --refinement
"""
from __future__ import annotations

import argparse
import csv
import json
import math
from pathlib import Path
import numpy as np

from geopympm.core import BackgroundGrid, ParticleSet
from geopympm.interpolation.cpdi import update_cpdi_domain
from geopympm.materials import LinearElastic
from geopympm.solvers import ExplicitMPMSolver

E = 1200.0
NU = 0.25
RHO = 1200.0
MATERIAL = LinearElastic(E, NU)
MU = MATERIAL.shear_modulus
LAM = MATERIAL.lame_lambda
CL = math.sqrt((LAM + 2 * MU) / RHO)
CT = math.sqrt(MU / RHO)
BOX0, BOX1 = 2.0, 10.0
CORE0, CORE1 = 4.5, 7.5
K = math.pi / 2
Q_L = np.array([K, K], dtype=float)
Q_T = np.array([K, 2 * K], dtype=float)
EL = Q_L / np.linalg.norm(Q_L)
ET = np.array([-Q_T[1], Q_T[0]]) / np.linalg.norm(Q_T)
AL, AT = 0.14, 0.18  # baseline, multiplied by dimensionless amplitude_scale
DT = 0.002
STEPS = 150
METHODS = ("mpm", "gimp", "cpgimp", "cpdi")


def _modes(amplitude_scale):
    return ((AL * amplitude_scale, Q_L, EL, CL),
            (AT * amplitude_scale, Q_T, ET, CT))


def exact_linear(reference_positions, t, amplitude_scale=0.25):
    """Closed-form mixed P/S solution in infinite linear plane-strain medium.

    Returns stress (xx, yy, zz, xy), displacement, velocity and F=I+grad(u).
    This is a *linear theory* reference only, not a finite-strain solution.
    """
    X = np.asarray(reference_positions, dtype=np.float64)
    if X.ndim != 2 or X.shape[1] != 2:
        raise ValueError("reference_positions must be shape (n,2)")
    u = np.zeros_like(X)
    v = np.zeros_like(X)
    grad_u = np.zeros((len(X), 2, 2))
    for A, q, e, c in _modes(amplitude_scale):
        w = c * np.linalg.norm(q)
        phase = X @ q
        u += (A/w * math.sin(w*t) * np.cos(phase))[:, None] * e
        v += (A * math.cos(w*t) * np.cos(phase))[:, None] * e
        grad_u += (-A/w * math.sin(w*t) * np.sin(phase))[:, None, None] * np.outer(e, q)
    F = grad_u + np.eye(2)[None, :, :]
    D = 0.5 * (grad_u + np.swapaxes(grad_u, 1, 2))
    tr = D[:, 0, 0] + D[:, 1, 1]
    sig = np.zeros((len(X), 4))
    sig[:, 0] = LAM * tr + 2 * MU * D[:, 0, 0]
    sig[:, 1] = LAM * tr + 2 * MU * D[:, 1, 1]
    sig[:, 2] = LAM * tr
    sig[:, 3] = 2 * MU * D[:, 0, 1]
    return dict(position=X+u, velocity=v, stress=sig, F=F)


def make_case(method='cpdi', *, h=0.5, ppc=2, amplitude_scale=0.25, dt=DT):
    if method not in METHODS: raise ValueError(f"invalid interpolation: {method}")
    if h <= 0 or ppc < 1 or dt <= 0 or amplitude_scale <= 0:
        raise ValueError('h, ppc, dt, amplitude_scale must all be positive')
    if not np.isclose(round(8/h)*h, 8.):
        raise ValueError('h must divide 8 m exactly')
    if not np.isclose(round(12/h)*h, 12.):
        raise ValueError('h must divide 12 m exactly')
    n = round((BOX1-BOX0)*ppc/h)
    xx = BOX0+(np.arange(n)+0.5)*h/ppc
    X, Y = np.meshgrid(xx, xx, indexing='xy')
    X0 = np.column_stack([X.ravel(),Y.ravel()])
    vel = exact_linear(X0, 0., amplitude_scale)['velocity']
    vol = np.full(len(X0), (h/ppc)**2)
    particle = ParticleSet(X0, vol*RHO, vol, velocity=vel,
                           domain_size=np.full((len(X0),2),h/ppc))
    grid = BackgroundGrid((0.,0.),(h,h),(round(12/h),round(12/h)))
    assert not np.any(grid.velocity_bc_mask)  # both x/y unconstrained
    if method=='cpdi': update_cpdi_domain(particle, grid)
    solver = ExplicitMPMSolver(particle,grid,MATERIAL,dt=dt,pic_fraction=0.,cfl=0.25,
                interpolation=method,stress_update='corotational',
                kinematics_update='exponential',advection_update='affine_exponential')
    core=np.all((X0>=CORE0)&(X0<=CORE1),axis=1)
    return X0,core,particle,grid,solver


def _relative_error(x, ref):
    return float(np.linalg.norm(np.asarray(x)-ref)/max(np.linalg.norm(ref),1e-13))


def _absolute_rms(x):
    x=np.asarray(x)
    return float(np.sqrt(np.mean(x*x)))


def assess(X0, core, p, t, amplitude_scale):
    ref=exact_linear(X0[core],t,amplitude_scale)
    calcstress=p.stress[core][:,[0,1,2,3]]
    f=p.deformation_gradient[core]
    # Two independent off-diagonal components should be present in the mixed P/S field.
    rot=np.arctan2(f[:,1,0]-f[:,0,1], f[:,0,0]+f[:,1,1])
    rr=ref['F']
    rrot=np.arctan2(rr[:,1,0]-rr[:,0,1],rr[:,0,0]+rr[:,1,1])
    return dict(
        stress_relative_l2=_relative_error(calcstress,ref['stress']),
        shear_stress_relative_l2=_relative_error(calcstress[:,3],ref['stress'][:,3]),
        velocity_relative_l2=_relative_error(p.velocity[core],ref['velocity']),
        displacement_absolute_rms_m=_absolute_rms(p.position[core]-ref['position']),
        F_absolute_rms=_absolute_rms(f-rr),
        polar_rotation_absolute_rms_deg=math.degrees(_absolute_rms(rot-rrot)),
        peak_polar_rotation_deg=math.degrees(float(np.max(np.abs(rot)))),
        peak_Fxy=float(np.max(np.abs(f[:,0,1]))),
        peak_Fyx=float(np.max(np.abs(f[:,1,0]))),
        min_detF=float(np.min(np.linalg.det(p.deformation_gradient))),
        max_core_displacement_m=float(np.max(np.linalg.norm(p.position[core]-X0[core],axis=1))),
    )


def cpdi_edge_mismatch(p, n_side):
    """Max/RMS endpoint disagreement for initially adjacent square domains.

    Diagnostic only: adjacent CPDI parallelograms need not share edges under
    spatially nonuniform deformation. Not an area-overlap or contact test.
    """
    if p.n_particles != n_side*n_side:
        raise ValueError('n_side must match structured initial particle lattice')
    F=p.deformation_gradient.reshape(n_side,n_side,2,2)
    x=p.position.reshape(n_side,n_side,2)
    sides=p.domain_size0.reshape(n_side,n_side,2)
    a=F[:,:,:,0]*(0.5*sides[:,:,0,None])
    b=F[:,:,:,1]*(0.5*sides[:,:,1,None])
    # Adjacent east/west faces, and north/south faces: two endpoints each.
    east=x[:,:-1]+a[:,:-1]
    west=x[:,1:]-a[:,1:]
    dx1=east-b[:,:-1]-(west-b[:,1:])
    dx2=east+b[:,:-1]-(west+b[:,1:])
    north=x[:-1,:]+b[:-1,:]
    south=x[1:,:]-b[1:,:]
    dy1=north-a[:-1,:]-(south-a[1:,:])
    dy2=north+a[:-1,:]-(south+a[1:,:])
    distances=np.concatenate([np.linalg.norm(z.reshape(-1,2),axis=1)
                   for z in (dx1,dx2,dy1,dy2)])
    return float(np.max(distances)),float(np.sqrt(np.mean(distances**2)))


def run_one(method='cpdi', *, h=0.5, ppc=2, amplitude_scale=0.25,
            dt=DT, steps=STEPS):
    X0,core,p,g,sol=make_case(method,h=h,ppc=ppc,amplitude_scale=amplitude_scale,dt=dt)
    initial_velocity=p.velocity.copy()
    mass0=float(p.mass.sum())
    mom0=np.sum(p.mass[:,None]*p.velocity,axis=0)
    oldcells=np.floor(p.position/h).astype(int)
    crossing=0
    max_fx=0.;max_fy=0.;max_ax=0.;max_ay=0.
    max_raw_acceleration=0.; peak_accel_info={}
    max_accel_mass_supported=0.
    max_momerr=0.
    samples=[]
    for step in range(steps):
        sol.step()
        max_fx=max(max_fx,float(np.max(np.abs(g.force_internal[:,0]))))
        max_fy=max(max_fy,float(np.max(np.abs(g.force_internal[:,1]))))
        max_ax=max(max_ax,float(np.max(np.abs(g.acceleration[:,0]))))
        max_ay=max(max_ay,float(np.max(np.abs(g.acceleration[:,1]))))
        magnitude=np.linalg.norm(g.acceleration,axis=1)
        i_peak=int(np.argmax(magnitude))
        if float(magnitude[i_peak])>max_raw_acceleration:
            max_raw_acceleration=float(magnitude[i_peak])
            peak_accel_info=dict(step=step+1,node_id=i_peak,
                nodal_mass_kg=float(g.mass[i_peak]),
                nodal_fx_N=float(g.force_internal[i_peak,0]),
                nodal_fy_N=float(g.force_internal[i_peak,1]))
        positive=g.mass[g.mass>0]
        if positive.size:
            # Diagnostic-only relative mass threshold: does not affect solver.
            supported=g.mass>1e-8*float(np.median(positive))
            if np.any(supported):
                max_accel_mass_supported=max(max_accel_mass_supported,
                    float(np.max(magnitude[supported])))
        mom=np.sum(p.mass[:,None]*p.velocity,axis=0)
        max_momerr=max(max_momerr,float(np.max(np.abs(mom-mom0))))
        cells=np.floor(p.position/h).astype(int)
        crossing+=int(np.count_nonzero(np.any(cells!=oldcells,axis=1)))
        oldcells=cells
        if step in (0,steps//2,steps-1):
            samples.append(dict(step=step+1,t_s=sol.time,**assess(X0,core,p,sol.time,amplitude_scale)))
    gaps=cpdi_edge_mismatch(p,round((BOX1-BOX0)*ppc/h)) if method=='cpdi' else (None,None)
    result=dict(method=method,h_m=h,ppc=ppc,amplitude_scale=amplitude_scale,
        steps=steps,dt_s=dt,t_s=sol.time,particles=p.n_particles,
        core_particles=int(core.sum()),
        mass_relative_error=abs(float(p.mass.sum())-mass0)/mass0,
        momentum_absolute_error_kg_m_s=max_momerr,
        max_nodal_force_x_N=max_fx,max_nodal_force_y_N=max_fy,
        max_nodal_acceleration_x=max_ax,max_nodal_acceleration_y=max_ay,
        max_raw_nodal_acceleration_m_s2=max_raw_acceleration,
        peak_nodal_acceleration_info=peak_accel_info,
        max_mass_supported_nodal_acceleration_m_s2=max_accel_mass_supported,
        particle_cell_crossings=crossing,
        max_particle_velocity_change_m_s=float(np.max(np.linalg.norm(p.velocity-initial_velocity,axis=1))),
        max_ballistic_position_difference_m=float(np.max(np.linalg.norm(p.position-(X0+initial_velocity*sol.time),axis=1))),
        cpdi_max_shared_edge_mismatch_m=gaps[0],
        cpdi_rms_shared_edge_mismatch_m=gaps[1],
        both_grid_components_unconstrained=bool(not np.any(g.velocity_bc_mask)),
        **assess(X0,core,p,sol.time,amplitude_scale))
    return result,samples,(X0,core,p)


def run_suite(*, refinement=False, amplitude_sweep=False, output='validation/results/stage10eb2',
              dt=DT, steps=STEPS):
    output=Path(output);output.mkdir(parents=True,exist_ok=True)
    cases=[];series=[]
    cpdi_core_fields=None
    main_h=.25
    for name in METHODS:
        print(f'Running {name}, h={main_h}, scale=0.25 ...',flush=True)
        r,s,snapshot=run_one(name,h=main_h,amplitude_scale=0.25,dt=dt,steps=steps)
        if name=='cpdi':
            init,mask,ps=snapshot
            cpdi_core_fields=(init[mask].copy(),ps.stress[mask,3].copy())
        print(f'  stress L2={r["stress_relative_l2"]:.5f} F RMS={r["F_absolute_rms"]:.5g}',flush=True)
        cases.append(r)
        for entry in s:series.append(dict(method=name,h_m=main_h,amplitude_scale=.25,**entry))
    if refinement:
        for h in (1.,.5):
            print(f'Running CPDI1 refinement h={h} ...',flush=True)
            r,s,_=run_one('cpdi',h=h,amplitude_scale=.25,dt=dt,steps=steps)
            cases.append(r)
            for entry in s:series.append(dict(method='cpdi',h_m=h,amplitude_scale=.25,**entry))
    if amplitude_sweep:
        for scale in (.1,.5,1.,3.):
            print(f'Running CPDI1 amplitude scale={scale} ...',flush=True)
            r,s,_=run_one('cpdi',h=.5,amplitude_scale=scale,dt=dt,steps=steps)
            cases.append(r)
            for entry in s:series.append(dict(method='cpdi',h_m=.5,amplitude_scale=scale,**entry))
    base=cases[:4]; cpdi=base[3]
    checks={
       'four_methods':len({v['method'] for v in base})==4,
       'both_velocity_components_free':all(v['both_grid_components_unconstrained'] for v in cases),
       'force_driven_both_components':all(v['max_nodal_force_x_N']>1e-3 and v['max_nodal_force_y_N']>1e-3 for v in cases),
       'not_ballistic_advection':all(v['max_ballistic_position_difference_m']>1e-5 for v in cases),
       'mixed_shear_and_rotation':cpdi['peak_Fxy']>1e-4 and cpdi['peak_Fyx']>1e-4 and cpdi['peak_polar_rotation_deg']>0.01,
       'mass_and_momentum':all(v['mass_relative_error']<1e-12 and v['momentum_absolute_error_kg_m_s']<1e-6 for v in cases),
       'positive_deformation':all(v['min_detF']>0 for v in cases),
       'finite_metrics':all(all(np.isfinite(v[k]) for k in ('stress_relative_l2','F_absolute_rms','polar_rotation_absolute_rms_deg')) for v in cases),
       'cpdi_reference_error_bounded':cpdi['stress_relative_l2']<0.6,
       'cpdi_domain_mismatch_finite':np.isfinite(cpdi['cpdi_max_shared_edge_mismatch_m']),
    }
    if refinement:
        coarse=next(v for v in cases if v['method']=='cpdi' and v['h_m']==1.)
        intermediate=next(v for v in cases if v['method']=='cpdi' and v['h_m']==.5)
        checks['cpdi_refinement_reduces_stress_error']=(cpdi['stress_relative_l2']<intermediate['stress_relative_l2']<coarse['stress_relative_l2'])
    if amplitude_sweep:
        strong=next(v for v in cases if v['method']=='cpdi' and v['amplitude_scale']==3.)
        checks['strong_2d_rotation_generated']=strong['peak_polar_rotation_deg']>5. and strong['peak_Fxy']>0.05 and strong['peak_Fyx']>0.05
        checks['strong_run_positive_F']=strong['min_detF']>0
        checks['strong_run_domain_mismatch_measured']=strong['cpdi_max_shared_edge_mismatch_m']>0
    checks={k:bool(v) for k,v in checks.items()}
    summary=dict(checks=checks,reference='exact 2D mixed oblique P/S plane waves in LINEAR plane-strain elastodynamics',
        caveat='Reference is not exact for finite-strain Jaumann hypoelastic response; free-surface effects excluded by central window and short-time finite propagation; no general bending/traction validation.',
        parameters=dict(E_pa=E,nu=NU,rho_kg_m3=RHO,cP_m_s=CL,cS_m_s=CT,dt_s=dt,steps=steps,
                        core_window_m=[CORE0,CORE1],particle_block_m=[BOX0,BOX1]),cases=cases)
    with open(output/'10EB2_summary.json','w') as f:json.dump(summary,f,indent=2)
    if cases:
        with open(output/'10EB2_cases.csv','w',newline='') as f:
            writer=csv.DictWriter(f,fieldnames=list(cases[0].keys()));writer.writeheader();
            for record in cases:
                writer.writerow({k:(json.dumps(v) if isinstance(v,dict) else v) for k,v in record.items()})
    if series:
        with open(output/'10EB2_history.csv','w',newline='') as f:
            writer=csv.DictWriter(f,fieldnames=list(series[0].keys()));writer.writeheader();writer.writerows(series)
    try:
        import matplotlib
        matplotlib.use('Agg')
        import matplotlib.pyplot as plt
        fig,axs=plt.subplots(1,2,figsize=(10.5,4))
        for name in METHODS:
            ss=[row for row in series if row['method']==name and row['h_m']==main_h and row['amplitude_scale']==.25]
            axs[0].plot([v['t_s'] for v in ss],[100*v['stress_relative_l2'] for v in ss],marker='o',label=name)
        axs[0].set(xlabel='Time (s)',ylabel='Stress relative L2 error (%)',title='2D mixed-wave stress');axs[0].legend();axs[0].grid(alpha=.25)
        refcases=[v for v in cases if v['method']=='cpdi' and v['amplitude_scale']==.25]
        axs[1].plot([v['h_m'] for v in sorted(refcases,key=lambda z:z['h_m'])],
                    [100*v['stress_relative_l2'] for v in sorted(refcases,key=lambda z:z['h_m'])],marker='o')
        axs[1].set(xlabel='Grid spacing h (m)',ylabel='Stress relative L2 error (%)',title='CPDI1 grid refinement');axs[1].grid(alpha=.25)
        fig.tight_layout();fig.savefig(output/'10EB2_summary.png',dpi=170);plt.close(fig)
        if cpdi_core_fields is not None:
            Xcore, shear_cpdi=cpdi_core_fields
            shear_ref=exact_linear(Xcore,steps*dt,.25)['stress'][:,3]
            nside=int(round((CORE1-CORE0)*2/main_h))
            ref_map=shear_ref.reshape(nside,nside)
            num_map=shear_cpdi.reshape(nside,nside)
            err_map=num_map-ref_map
            extent=(CORE0,CORE1,CORE0,CORE1)
            vmax=max(float(np.max(np.abs(ref_map))),float(np.max(np.abs(num_map))))
            fig2,ax2=plt.subplots(1,3,figsize=(12,3.6),constrained_layout=True)
            for ax,z,title in zip(ax2,(ref_map,num_map,err_map),
                    ('Exact linear P/S reference','CPDI1 Jaumann-MPM','CPDI1 minus linear reference')):
                value= vmax if title != 'CPDI1 minus linear reference' else max(float(np.max(np.abs(err_map))),1e-12)
                im=ax.imshow(z,origin='lower',extent=extent,cmap='RdBu_r',vmin=-value,vmax=value)
                ax.set(xlabel='x (m)',ylabel='y (m)',title=title)
                fig2.colorbar(im,ax=ax,shrink=.8,label='sigma_xy (Pa)')
            fig2.savefig(output/'10EB2_shear_field.png',dpi=170);plt.close(fig2)
    except ImportError:pass
    print('CHECKS:',checks);print('RESULTS:',output)
    return summary


def main():
    ap=argparse.ArgumentParser()
    ap.add_argument('--refinement',action='store_true')
    ap.add_argument('--amplitude-sweep',action='store_true')
    ap.add_argument('--output',default='validation/results/stage10eb2')
    args=ap.parse_args()
    result=run_suite(refinement=args.refinement,amplitude_sweep=args.amplitude_sweep,output=args.output)
    if not all(result['checks'].values()):raise SystemExit('Some Stage 10E-B2 checks failed')

if __name__=='__main__':main()
